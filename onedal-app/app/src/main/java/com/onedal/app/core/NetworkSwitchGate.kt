package com.onedal.app.core

/**
 * 🔄 **배차망 전환 관문 — 화면을 보는 그 자리에서 갈아탄다** (기사님 확정)
 *
 * 기사님: *"실시간으로 대응해 주면 되는데 미리 설정하고 그 앱만 꼭 써야 하는 건 아니잖아."*
 * → 라디오는 **표시**일 뿐이고 **화면이 원천**이다 (규칙 ③).
 *
 * ── 🔴 «몇 초 지켜보기» 없이 바로 갈아탄다 ──
 * «같은 화면이 N초 안정되면 전환»으로 하면, 다음 접근성 이벤트가 와야 «N초 지났나»를 물을 수 있다.
 * 그래서 **이벤트가 안 오는 정지 화면(픽커 홈)에서는 전환이 영영 안 되고**, 그동안 앱은 콜을
 * 한 건도 안 읽으며 서버는 이전 배차망으로 알고 있다. 4초 안정을 기다리게 했을 때의 실측:
 *
 * | 실측 | 무슨 일 |
 * |---|---|
 * | 인성 화면으로 감 | **11.5초** 뒤에야 전환 |
 * | 픽커 화면으로 감 | 2분 넘게 **전환 안 됨** |
 *
 * 🟢 기다릴 이유가 없다 — **패키지 이름은 추측이 아니라 사실이다.** 화면에 픽커가 떠
 *    있으면 픽커 화면이다. 기다리는 동안 얻는 것은 없고(그 사이 콜을 버린다),
 *    잃는 것(전환 시 지문·세션 리셋)은 기다려도 똑같이 일어난다.
 */
object NetworkSwitchGate {

    /**
     * 갈아탈 배차망을 돌려준다. `null` 이면 갈아탈 일이 없다.
     * 모르는 패키지(카톡·런처 등)는 관문의 일이 아니다 — 어차피 «알 수 없는 화면»으로 흐른다.
     */
    fun switchTargetFor(screenNetwork: String?, current: String): String? =
        if (screenNetwork != null && screenNetwork != current) screenNetwork else null
}
