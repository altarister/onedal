package com.onedal.app.core

/**
 * 🔄 **배차망 전환 관문 — 화면을 보는 그 자리에서 갈아탄다** (기사님 확정 2026-09-02)
 *
 * 기사님: *"실시간으로 대응해 주면 되는데 미리 설정하고 그 앱만 꼭 써야 하는 건 아니잖아."*
 * → 라디오는 **표시**일 뿐이고 **화면이 원천**이다 (규칙 ③).
 *
 * ── 🔴 여기에 «몇 초 지켜보기»를 다시 넣지 않는다 ──
 * 2026-08-31~09-02 에 «같은 배차망 화면이 **4초** 안정되면 전환»이 있었다. 그 4초는
 * **근거가 어디에도 없었다** — 코드 주석 세 줄뿐이고 검사도 문서도 없었다
 * (규칙 ⑤-4 ② 가 빈 채 태어난 값). 그리고 값을 치른 것은 컸다:
 *
 * | 실측 2026-09-02 | 무슨 일 |
 * |---|---|
 * | 15:17:05 → 15:17:16.8 | 인성 화면으로 갔는데 **11.5초** 뒤에야 전환 |
 * | 15:19:33 → 2분 넘게 | 픽커 화면으로 갔는데 **영영 전환 안 됨** |
 *
 * 옛 방식은 시각만 적어 두고 *"다음 접근성 이벤트가 오면 4초 지났나 물어본다"* 였다.
 * 그래서 **이벤트가 안 오는 정지 화면(픽커 홈)에서는 물어볼 기회가 영영 안 왔다.**
 * 그동안 앱은 «판을 버린다»며 콜을 **한 건도 안 읽었고**, 서버는 옛 배차망으로 알고 있었다.
 *
 * 🟢 기다릴 이유가 없다 — **패키지 이름은 추측이 아니라 사실이다.** 화면에 픽커가 떠
 *    있으면 픽커 화면이다. 기다리는 동안 얻는 것은 없고(그 사이 판을 버린다),
 *    잃는 것(전환 시 지문·세션 리셋)은 기다려도 똑같이 일어난다.
 */
object NetworkSwitchGate {

    /**
     * 갈아탈 배차망을 돌려준다. `null` 이면 갈아탈 일이 없다.
     * 모르는 패키지(카톡·런처 등)는 관문의 일이 아니다 — 어차피 «알 수 없는 화면»으로 흐른다.
     */
    fun switchTargetFor(screenNetwork: String?, current: String): String? =
        if (screenNetwork != null && screenNetwork != current) screenNetwork else null
}
