package com.onedal.app.plugins.insung

import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * 📏 **상차 거리 «1.4» 를 차종(1.4t)으로 읽지 않는다** (시뮬레이터 «7지점 한 바퀴» 폰 판)
 *
 * 인성 리스트 한 줄은 `상차거리, 배송거리, 시각/상차지, 하차지, 차종, 요금` 이다.
 * 파서는 차종 토큰을 닻으로 잡고 **바로 다음 숫자를 요금**으로 읽는다.
 *
 * 🔴 그런데 차종 토큰에 **«1.4»(1.4t 의 약자)** 가 있다 — 상차 거리 칸이 마침 1.4km 면 그 칸이 닻이 된다.
 *    같은 5t · 15만 원 콜을 두 번 읽었는데 (서버 intel 에 남은 줄 글자 그대로):
 * ```
 * 04:27  2.2, 15.2, 낼8시8/초월읍, 중리동, 5t, 15.0      → 차종 5t  · 150,000원  (맞다)
 * 13:04  1.4, 15.2, 오후5시6/초월읍, 중리동, 5t, 15.0    → 차종 1.4 · 152,000원  (배송거리 15.2 를 요금으로)
 * ```
 * 그 판은 «1.4» 도 허용 차종 밖이라 **우연히** 차단이 맞았다. 허용 차종 콜의 상차 거리가 1.4·2.5·3.5km 면
 * 차종·요금을 틀리게 읽어 잘못 거르거나 잘못 잡는다.
 */
class VehicleFareAnchorTest {

    private fun read(row: String) = InsungParser.readVehicleAndFare(row.split(", "))

    @Test
    fun `상차 거리가 1점4 여도 차종은 5t 요금은 15만 - 그날 13시04분 줄`() {
        assertEquals("5t" to 150_000, read("1.4, 15.2, 오후5시6/초월읍, 중리동, 5t, 15.0"))
    }

    @Test
    fun `상차 거리가 2점2 면 원래도 맞았다 - 그날 04시27분 줄`() {
        assertEquals("5t" to 150_000, read("2.2, 15.2, 낼8시8/초월읍, 중리동, 5t, 15.0"))
    }

    @Test
    fun `상차 거리 1점4 에 다마스 콜 - 차종 다 요금 5만`() {
        assertEquals("다" to 50_000, read("1.4, 3.3, 사음동, 중리동, 다, 5.0"))
    }

    @Test
    fun `상차 거리 2점5 에 다마스 콜 - 차종 다 요금 3만`() {
        assertEquals("다" to 30_000, read("2.5, 5.8, 중리동, 신둔면, 다, 3.0"))
    }

    @Test
    fun `진짜 1점4t 콜은 그대로 1점4`() {
        assertEquals("1.4" to 50_000, read("3.2, 10.1, 오후5시6/초월읍, 중리동, 1.4, 5.0"))
    }

    @Test
    fun `상차 거리도 차종도 1점4 면 뒤의 차종 칸을 읽는다`() {
        assertEquals("1.4" to 50_000, read("1.4, 2.5, 오후5시6/초월읍, 중리동, 1.4, 5.0"))
    }

    @Test
    fun `뭉친 노드 라2점2 는 그대로 읽는다`() {
        assertEquals("라" to 22_000, read("3.2, 10.1, 초월읍, 중리동, 라2.2"))
    }
}
