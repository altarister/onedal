/**
 * 🌈 **콜 색표 — 세 축을 안 겹치게 가른다** (기사님 확정 2026-09-04)
 *
 * 기사님: *"무지개 색으로 콜의 배경 색을 정하고
 * 채도로 상차지 하차지를 결정하자. 채도가 높으면 상차지 낮으면 하차지.
 * 테두리는 아직 안 간 곳 하얀색, 지나가면 회색."* → **뒤집혔다** (아래 `callNodeStroke`).
 *
 * ── 왜 ──
 * 예전에는 색이 **두 가지를 동시에 말하려다 둘 다 못 했다** —
 * 마커 바탕은 상차/하차(초록·로즈)를, 가는 테두리는 콜을 말했다. 그래서
 * *"지도 아이콘 색과 콜 리스트가 괴리가 커서 운전 중 직관적이지 못하다"*(기사님 실주행 09-03).
 *
 * ── 규칙 ──
 * | 눈이 보는 것 | 답하는 질문 |
 * |---|---|
 * | **색상(hue)** | 몇 번 콜인가 — 빨 초 파 보 |
 * | **밝기** | 상차인가(밝고 선명) 하차인가(같은 색으로 깊다) |
 * | **테두리** | 다녀왔나 — 지나감(흰 링, «완료 동그라미») · 아직(링 없음) |
 *
 * 🔴 **넷만 쓴다** — 실물에서 여섯을 보고 기사님이 줄이셨다: *"빨 주 가 비슷해 보인다."*
 *    노랑도 뺐다(채도를 낮추면 회색이 되어 «하차»가 «지나간 곳»처럼 보였다).
 * 🔴 **1번은 순수 빨강이 아니라 토마토색이다.** 순수 빨강은 판정 🔴(연산 실패)와
 *    지각 경고가 이미 쓴다 — 1번 콜이 «급한 콜»로 읽히면 안 된다 (규칙 ⑤-3: 색이 곧 결정).
 * 🔴 **색이 모자라면 되돌아 쓴다**(7번 = 1번 색). 색을 지어내지 않는다 (규칙 ④).
 *
 * ⚠️ 지도는 두 테마 모두 **회색조**로 깔린다(`grayscale(1) contrast(0.72)`).
 *    그래서 흰 링이 양쪽에서 산다.
 */

export type UiTheme = 'dark' | 'light';
export type StopKind = 'pickup' | 'dropoff';

/**
 * 빨(토마토) · 초 · 파 · 보 — **넷** (기사님 2026-09-04: *"빨 주 가 비슷해 보인다.
 * 빨 초 파 보 이렇게 4개만 해보자"*).
 *
 * 🔴 **색마다 밝기(L)를 따로 준다.** 같은 L 이라도 초록은 훨씬 밝아 보여서,
 *    한 값으로 맞추면 초록 위의 **흰 글자가 안 읽힌다.** 눈에 비슷한 밝기로 맞춘 값이다.
 * 🔴 **5번째 콜부터 되돌아 쓴다**(5번=빨강). 동시에 넷을 넘길 일이 없다는 판단 —
 *    한 번에 세 콜이 실제 최대다.
 */
export const CALL_TONES = [
    /* 상차(진하고 밝다) · 하차(같은 색으로 깊다) — 색마다 값을 따로 잡았다 */
    { hue: 8,   pick: [80, 46], drop: [58, 39] },   // 빨 — 토마토. 순수 빨강은 판정 🔴·지각 경고가 쓴다
    { hue: 145, pick: [74, 31], drop: [54, 26] },   // 초 — 눈에 가장 밝게 보여 가장 어둡게 잡는다
    { hue: 205, pick: [78, 42], drop: [58, 36] },   // 파
    { hue: 288, pick: [68, 47], drop: [52, 39] },   // 보
] as const;

/** 몇 번 콜인가 → 색조. 넷을 넘으면 되돌아 쓴다 */
export function callTone(callNo: number) {
    const i = (Math.max(1, callNo) - 1) % CALL_TONES.length;
    return CALL_TONES[i];
}

/**
 * 🎨 **콜 번호 + 상차/하차 → 마커 바탕색.**
 *
 * 🔴 **채도만 낮추지 않는다** (기사님 실물 지적 2026-09-04:
 *    *"붉은색에 채도를 어떻게 넣은 거지? 같은 계열 같은 느낌이 아닌 것 같아"*).
 *    빨강은 채도를 30%까지 낮추면 `rgb(172,116,105)` — **갈색**이 된다.
 *    다른 색은 버티는데 빨강만 무너져 «같은 콜»로 안 읽혔다.
 *
 *    그래서 **채도는 덜 낮추고 밝기로 가른다** — 상차는 밝고 선명, 하차는 **같은 색으로 깊게.**
 *    빨강이면 `선명한 빨강 ↔ 벽돌빛 빨강` 이라 한 집안인 게 보인다.
 *
 * 🔴 값은 **흰 글자 대비를 재서** 잡았다 (전부 4.4:1 이상 · 기사님: *"글은 흰색으로"*).
 *    밝기를 올리면 여기가 먼저 무너진다 — 특히 초록.
 *
 * ⚠️ **차이를 한 번 좁혔다** (기사님 2026-09-04: *"채도 차이가 너무 많이 나는 것 같아
 *    조금만 밝게 해줘"*). 밝기차 13·10·13·14 → **7·5·6·8.**
 *    🔴 **초록만 여지가 없다** — 눈에 가장 밝은 색이라 흰 글자를 쓰려면 상차를 L31 까지
 *       눌러야 하고, 하차는 그보다 더 어두워야 한다. 청록 쪽으로 옮겨도 나아지지 않는다
 *       (h145~175 를 재 봤다). 그래서 초록의 차이(5)가 가장 좁다 — **채도로 버틴다.**
 *
 * ⚠️ 밝은 테마는 지도가 더 밝으므로 세 칸 더 어둡게 — 마커가 배경에서 떨어진다.
 */
export function callNodeFill(callNo: number, stop: StopKind, theme: UiTheme): string {
    const t = callTone(callNo);
    const [sat, light] = stop === 'pickup' ? t.pick : t.drop;
    return `hsl(${t.hue} ${sat}% ${theme === 'dark' ? light : light - 3}%)`;
}

/**
 * 마커 안 번호 글자색 — **언제나 흰색** (기사님 확정 2026-09-04).
 * 위 `callNodeFill` 의 어둡기가 그 전제다.
 */
export function callNodeText(_stop: StopKind, _theme: UiTheme): string {
    return 'rgb(255, 255, 255)';
}

/**
 * 🖊️ **테두리 = 다녀왔나 — «완료하면 동그라미 친다»** (기사님 확정 2026-09-04).
 *
 * *"테두리가 있으면 지나간 거고 없으면 아직 안 간 거고. 뭔가 완료하면
 * 동그라미 하는 거랑 같은 의미로 처리하면 어때?"*
 *
 * 🔴 **처음에는 반대였다** — 아직(흰색) · 지나감(회색). 그런데 실물에서
 *    회색 테두리가 **1px 에서 안 보였다.** 뒤집으니 둘 다 산다:
 *    지나간 곳은 흰 링이 또렷하고, 아직 안 간 곳은 링이 아예 없다.
 * 🔴 **«없음»을 바탕색으로 만든다.** 테두리를 지우면 동그라미가 1px 작아져
 *    두 상태의 크기가 달라진다 — 같은 색을 둘러 크기를 붙잡는다 (기사님 안 그대로).
 */
export function callNodeStroke(visited: boolean, fill: string): string {
    return visited ? 'rgb(255, 255, 255)' : fill;
}
