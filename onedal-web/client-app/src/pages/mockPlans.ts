/**
 * ⟳ **다시 물은 판을 만든다** — 순서·경로선·구간 분이 통째로 갈린다.
 *
 * 🔴 콜 목록도 **다시 파생시킨다** — 순서가 바뀌면 정거장 번호가 밀리므로
 *    콜이 가리키는 번호도 함께 바뀌어야 한다 (규칙 ③).
 */
export function reaskedPlan(plan: MockPlan): MockPlan {
    const r = REASKED[plan.calls as 3 | 4 | 5];
    return {
        ...plan,
        stops: r.stops, legMinutes: r.legMinutes, polyline: r.polyline,
        totalKm: r.totalKm, totalMin: r.totalMin,
        drivenTrail: plan.drivenTrail,
        callList: callsFor(r.stops),
        source: `⟳ 다시 물어 나온 순서 — ${r.stops.map(s => s.name).join(' → ')}`,
    };
}

/** ⟳ 를 누르면 **무엇이 달라지는가** — 같은 시각에 물은 두 순서의 차이다 */
export function reaskCost(plan: MockPlan) {
    const r = REASKED[plan.calls as 3 | 4 | 5];
    return {
        km: +(r.totalKm - r.asIsKm).toFixed(1),
        min: r.totalMin - r.asIsMin,
        asIs: `${r.asIsKm}km / ${r.asIsMin}분`,
        reasked: `${r.totalKm}km / ${r.totalMin}분`,
    };
}

