/**
 * 🔒 **화면에 콜이 둘이 되는 순간 경로 방침이 잠긴다** (기사님 확정 2026-08-19 ·
 * 2026-09-05 두 번 정정).
 *
 * *"2건 이상이면 선택되지 못한 버튼을 숨긴다 — 어떤 것이 선택돼 있는지는 보이고,
 *   경로는 바꿀 수 없게."* · *"합짐 잡기 전까지 바꿀 수 있어야 해."*
 * *"합짐1 심사 때 경로를 바꿀 수 없다 — **이미 그 경로로 들어온 콜**일 테니까."*
 *
 * 🔴 **마지막 한 줄이 규칙의 뿌리다.** 합짐은 **첫짐 경로 위에서 산출된 콜**이다.
 *    그 경로를 바꾸면 «가는 길에 있다»는 산출 근거 자체가 사라진다 —
 *    심사 중이라고 열어 두면 **자기를 불러온 경로를 자기가 지우는** 꼴이다.
 *    그리고 방침은 주행 시간을 바꾸므로 **이미 잡은 약속과도 어긋난다.**
 *
 * 그래서 세는 것은 «확정된 콜»이 아니라 **«화면에 올라 있는 콜»** 이다 — 심사 중인 것도 센다.
 *
 *   첫콜 심사   0 + 1 = 1  🔓 열림 — 붙일 콜이 하나뿐이니 경로를 골라 본다
 *   첫콜 확정   1 + 0 = 1  🔓 열림
 *   합짐1 심사  1 + 1 = 2  🔒 잠김
 *   합짐1 확정  2 + 0 = 2  🔒 잠김
 *
 * ⚠️ **두 번 고쳤다.** 실물이 원래 `liveRoute.length >= 2`(심사 포함)로 **맞았는데**,
 *    거기 붙은 `&& !anyEvaluating` 예외가 구멍을 냈다. 0819 의 «심사 중에는 열어 둔다»는
 *    **첫콜 심사**를 말한 것이었는데 모든 심사로 번졌다. 예외를 빼니 원래 식으로 돌아왔다.
 *
 * @param callsOnScreen 화면에 올라 있는 콜 수 — **심사 중인 것도 센다**
 */
export function isPriorityLocked(callsOnScreen: number): boolean {
    return callsOnScreen >= 2;
}

/**
 * 🆕 **판이 바뀐 콜이 들어오면 다시 열린다 — 콜이 몇이든** (기사님 확정 2026-09-13 · R7).
 *
 * 기사님: *"파주로 설정하고 2개 잡고 하나 마무리했다. 하나 남은 상황에서 목적지를 바꾸었어.
 * 마름모가 둘인 상황에서 **바뀐 목적지 방향으로 콜이 찍히면 그때는 경로 변경 할 수 있다**."*
 * *"**몇 개가 남아 있든 간에 목적지가 바뀐 콜이 있으면**이 맞아."*
 *
 * ── 왜 열어도 되나 ──
 * 잠그는 근거(R2)는 «합짐은 **첫짐 경로 위에서 산출된 콜**이라, 그 경로를 바꾸면 자기를
 * 불러온 근거가 사라진다»였다. 그런데 **새 목적지 콜은 새 그물에서 온 것**이다 —
 * 옛 경로가 그 콜을 불러온 것이 아니므로 매일 이유가 없다. 목업이 그 화면을 이미 그린다:
 *
 *     ① 송정동 → ③ 내유동   🎯 파주시
 *     ② 장암동 → ④ 송정동   🎯 복귀(집)     ← 판이 다른 첫짐이 들어온 순간
 *
 * 🔴 **정거장 순서와는 무관하다.** 판이 달라도 콜은 «가장 싸게 끼워 넣는다» (⑮ §4) —
 *    「자기 판 그룹으로 뒤에 붙는다」는 2026-09-08 에 폐기된 옛 규칙이다
 *    (판을 가르니 합짐이 합짐이 아니게 됐다 · 실측 157.3km → 83.4km).
 *    위 예시의 번호가 ①②③④ 로 섞인 것이 그 증거다.
 * 🔴 **「판」은 «잡을 당시의 목적지»다** — 나중에 목적지를 바꿔도 그 콜의 판은 안 바뀐다.
 *
 * @param goalsOnScreen 화면에 올라 있는 콜들의 **판 이름** — 심사 중인 것도 센다.
 *                      모르는 콜은 넣지 않는다 (지어내지 않는다 · 규칙 ④).
 */
export function isPriorityLockedByGoals(goalsOnScreen: Array<string | null | undefined>): boolean {
    if (goalsOnScreen.length < 2) return false;          // R3 — 첫 콜 심사는 열린다
    const known = goalsOnScreen.filter((g): g is string => !!g);
    /* 🔴 **판을 하나도 모르면 콜 수로 판단한다** — 모른다고 열어 주면 R2 가 통째로 풀린다.
       옛 콜(칸이 생기기 전에 잡은 것)이 섞여도 안전한 쪽으로 기운다 */
    if (known.length === 0) return true;
    return new Set(known).size < 2;                      // 판이 하나뿐이면 잠긴다
}

