/**
 * 🔴 **앱인가 브라우저인가 — 판단은 여기 하나다** (기사님 실측 2026-08-26)
 *
 * 기사님: *"집에서 브라우저로 http://localhost:3000/ 으로 접속했는데 v2 로 보여."*
 *
 * 예전 무늬는 이랬다:
 *
 *     /^https?:\/\/localhost(:\d+)?$/          ← `(:\d+)?` 가 포트를 허용한다
 *
 * Capacitor 가 번들을 `https://localhost`(**포트 없음**)에서 띄우는 걸 잡으려던 것인데,
 * **개발 브라우저의 `http://localhost:3000` 도 그대로 맞았다.** 그래서 브라우저가
 * 관제앱으로 오인되어 `apiBase()` 가 **라이브**를 돌려줬고 —
 *
 *   · 로그인이 라이브로 가서 라이브 토큰이 저장되고
 *   · 기기 이름이 `v2`(라이브 DB)로 보이고
 *   · 로컬 서버 로그에는 아무것도 안 남는데 화면은 멀쩡히 도는
 *
 * 상태가 됐다. 로컬을 고치며 라이브를 보고 있었던 것이다. `localStorage` 를 지워도
 * 안 고쳐진다 — 저장값이 없으면 **바로 이 판단**으로 떨어지기 때문이다.
 *
 * ⚠️ 포트가 유일한 구분점이다. Capacitor 는 포트를 안 붙이고, 개발 서버는 늘 붙는다
 *    (`:3000` 관제웹 · `:5173` 시뮬레이터 · `:4173` preview).
 */
export function isAppOrigin(origin: string): boolean {
    return /^https?:\/\/localhost$/.test(origin);
}
