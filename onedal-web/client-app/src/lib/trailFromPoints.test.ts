import { describe, it, expect } from 'vitest';
import { trailFromPoints } from './driveStep';

/**
 * 👣 **새로고침해도 달린 자취가 남아야 한다** (기사님 2026-09-12 밤:
 *    *"카카오라인과 내 궤적이 같이 있어야 얼마나 잘못갔는지 확인할 수 있을 것 같아"*).
 *
 * ── 무엇이 문제였나 ──
 * `drivenTrailStore` 는 **브라우저 메모리에만** 쌓는다 (`local-gps-update` 를 듣는다).
 * 서버에서 불러오는 문이 없어서, 새로고침하면 `segments: []` 로 시작하고 **겹쳐 볼
 * 자취가 아예 없었다.** 장부(`gps_tracks`)에는 그날 점이 다 남아 있는데 화면이 안 읽었다.
 *
 * 🔴 **쌓는 규칙은 한 벌이어야 한다** (규칙 ③). 되살린 자취가 라이브와 다른 모양이면
 *    새로고침 전후로 **같은 주행이 다른 선**으로 보인다. 그래서 여기도 `pushTrail` 을
 *    그대로 쓴다 — 제자리(50m 안)는 안 쌓고, 2km 넘게 튀면 구간을 끊는다.
 *
 * ⚠️ 장부는 **콜별로** 읽히므로(`?orderId=`) 여러 벌이 섞여 온다 — **시각으로 다시 줄을
 *    세워야** 한다. 안 그러면 콜 경계에서 선이 되돌아가는 지그재그가 생긴다.
 */
const p = (atMs: number, x: number, y: number) => ({ atMs, x, y });
/**
 * 📏 **걸음은 현실 크기로 준다** — 위도 37.3 에서 경도 **0.01° ≈ 0.9km** 다.
 *    처음에 0.1°(≈8.9km) 로 적었다가 `pushTrail` 이 «순간이동»으로 보고 구간을 끊어
 *    검사가 헛돌았다. 50m~2km 사이라야 «이어 달린 것»이다.
 */

describe('👣 장부의 점을 자취로', () => {

    /** 🔴 콜별로 받아 섞여 와도 **시각 순**으로 줄을 세운다 */
    it('🔴 시각 순으로 이어 붙인다 (콜별로 섞여 와도)', () => {
        const segs = trailFromPoints([
            p(3000, 127.12, 37.30),     // 뒤 콜의 점이 먼저 왔다
            p(1000, 127.10, 37.30),
            p(2000, 127.11, 37.30),
        ]);
        expect(segs).toHaveLength(1);
        expect(segs[0].map(v => v.lng)).toEqual([127.10, 127.11, 127.12]);
    });

    /** 🔴 제자리(50m 안)는 안 쌓는다 — 라이브와 **같은 규칙**이라야 한다 */
    it('🔴 제자리 점은 안 쌓는다 (정차 잡음)', () => {
        const segs = trailFromPoints([
            p(1000, 127.10, 37.30),
            p(2000, 127.1000, 37.30001),   // 몇 m
            p(3000, 127.1000, 37.30002),
        ]);
        expect(segs[0]).toHaveLength(1);
    });

    /** 🔴 2km 넘게 튀면 **구간을 끊는다** — 순간이동은 주행이 아니다 */
    it('🔴 크게 튀면 구간이 갈린다', () => {
        const segs = trailFromPoints([
            p(1000, 127.10, 37.30),
            p(2000, 127.11, 37.30),
            p(3000, 127.90, 37.30),        // 한참 떨어진 자리
        ]);
        expect(segs).toHaveLength(2);
    });

    it('빈 입력이면 빈 자취다 — 지어내지 않는다', () => {
        expect(trailFromPoints([])).toEqual([]);
    });

    /** ⚠️ 좌표를 모르는 행은 버린다 (장부에 null 이 섞일 수 있다 · 규칙 ④) */
    it('좌표가 없는 점은 버린다', () => {
        const segs = trailFromPoints([
            p(1000, 127.10, 37.30),
            { atMs: 2000, x: null as unknown as number, y: 37.30 },
            p(3000, 127.11, 37.30),
        ]);
        expect(segs[0].map(v => v.lng)).toEqual([127.10, 127.11]);
    });
});
