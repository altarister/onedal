/**
 * 🕐 **화면에 시각을 적는 유일한 자리** (기사님 지적 2026-08-23).
 *
 * 기사님: *"`방금 1건 → 통과 0 · 차종 1` 같은 게 나오니까 **멈춰 있는 것 같아.**
 * 보내온 마지막 시간을 쓰는 것이 더 좋을 것 같다."*
 *
 * 🔴 **`방금` · `3분 전` 같은 상대시각을 쓰지 않는다.** 그것은 **다시 그려져야만 참인 말**이라,
 *    폰이 끊겨 화면이 안 그려지면 문구가 숫자와 **함께 멈춘다** — 고치려던 거짓말이
 *    모양만 바꿔 돌아온다. 절대시각은 안 그려져도 거짓이 되지 않는다.
 * 🔴 **초까지 적는다.** 분까지만 적으면 30초 전과 90초 전이 같아 보여서
 *    *"움직이고 있나"* 라는 원래 질문에 답하지 못한다.
 *
 * ⚠️ 포맷을 여기 하나로 둔다 — 여러 자리에서 각자 만들면 같은 화면에 `20:39:13` 과
 *    `오후 8:39` 가 나란히 뜬다 (규칙 ③: 파생값은 한 곳에서).
 */
export function formatClock(at?: number | null): string | null {
    if (!at) return null;
    const d = new Date(at);
    const pad = (n: number) => String(n).padStart(2, '0');
    return `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`;
}
