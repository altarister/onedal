/**
 * 🧬 **경로가 갈렸나 — 값으로 보는 지문**.
 *
 * ── 왜 따로 뺐나 ──
 * 모의 주행은 «지금 달리는 경로»의 인덱스를 들고 걷는다. 경로가 갈리면 인덱스를 다시
 * 잡아야 하는데, **«갈렸나»를 무엇으로 보느냐**에 따라 이렇게 넘어진다:
 *
 *   ⓐ `length` 만   → 점 수가 같은 다른 경로에 **지난 인덱스**를 써 수 km 를 뛴다
 *   ⓑ 참조(`!==`)   → `sync-active-orders` 마다 새 배열이라 **매 틱 다시 잡아** 걸음이 끊긴다
 *   ⓒ 양끝 + 길이   → 느슨하다. **콜이 끝나 경로가 다시 짜여도 그 셋이 같으면** 또 뛴다
 *
 * 🔴 **중간을 봐야 한다.** 같은 두 점을 잇는 길은 여럿이다 — 콜이 빠지면 경유가 바뀌는데
 *    출발지·목적지·점 수는 그대로일 수 있다. 그 차이는 **가운데에만** 있다.
 * 🔴 **값으로 본다** — 값이 같으면 같은 지문이어야 한다 (ⓑ).
 * ⚠️ **점을 전부 이어 붙인 문자열 대신 해시로 접는다** — 2,000점이면 문자열이 수만 자다
 *    (`sync` 가 올 때마다 도는 자리라 싸야 한다). 표본만 보면 가운데 한 점이 바뀐 것을
 *    놓친다 — 경유가 하나 빠지는 일이 정확히 그 모양이다.
 *
 * 🔬 검사는 `routeSignature.test.ts` — 특히 «양끝·점 수가 같아도 중간이 다르면 다르다».
 */
export interface RoutePoint { x: number; y: number }

/** 좌표를 지문에 넣을 때의 자릿수 — 카카오 폴리라인은 소수점 이하가 길다 */
const PRECISION = 1e5;

/**
 * 🔢 **한 점씩 섞어 32비트로 접는다** (FNV-1a 변형).
 *
 * 🔴 **모든 점을 섞는다.** 양끝+가운데 몇 곳만 보는 표본은 2,000점짜리 경로에서
 *    **가운데 한 점이 바뀐 것**을 놓친다. 경유가 하나 빠지는 일이 정확히 그 모양이다.
 * ⚠️ **그래도 싸다** — 점당 곱셈 둘이고 문자열을 안 만든다. 2,000점이면 4,000번,
 *    `sync-active-orders` 가 올 때만 돈다 (매 틱이 아니다).
 */
function fold(h: number, v: number): number {
    h ^= v;
    /* FNV 소수 16777619 — 32비트 안에서 잘 흩어진다 */
    return Math.imul(h, 16777619);
}

export function routeSignature(points?: RoutePoint[] | null): string {
    const n = points?.length ?? 0;
    if (!points || n === 0) return '';

    let h = 0x811c9dc5;
    for (const p of points) {
        h = fold(h, Math.round(p.x * PRECISION));
        h = fold(h, Math.round(p.y * PRECISION));
    }
    /* 🔴 길이를 함께 적는다 — 해시가 우연히 겹쳐도 점 수가 다르면 다른 경로다 */
    return `${n}:${(h >>> 0).toString(36)}`;
}
